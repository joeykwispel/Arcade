//! Every word the game shows, in English and Dutch. Names of tools and bugs stay English in both: that's what
//! Dutch developers call them too. `{name}` placeholders are filled in with [`fill`].

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Lang {
    En,
    Nl,
}

impl Lang {
    pub fn from_code(code: u32) -> Lang {
        if code == 1 { Lang::Nl } else { Lang::En }
    }
}

